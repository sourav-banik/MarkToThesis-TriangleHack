"use client";

import { useMemo, useState } from "react";
import type { ReasoningReview } from "@/features/ai/contracts";

type EvidenceDraft = {
  id: string;
  title: string;
  sourceUrl: string;
  publisher: string;
  publishedAt: string;
  retrievedAt: string;
  excerpt: string;
};
const newEvidence = (): EvidenceDraft => ({
  id: crypto.randomUUID(),
  title: "",
  sourceUrl: "",
  publisher: "",
  publishedAt: "",
  retrievedAt: new Date().toISOString().slice(0, 16),
  excerpt: "",
});
function iso(value: string) {
  return new Date(value).toISOString();
}

export function ReasoningReviewPanel({
  claimId,
  assumptions,
  review,
  canManage = false,
}: {
  claimId: string;
  assumptions: { id: string; statement: string }[];
  review?: ReasoningReview | null;
  canManage?: boolean;
}) {
  const [evidence, setEvidence] = useState<EvidenceDraft[]>([newEvidence()]);
  const [busy, setBusy] = useState(false);
  const [message, setMessage] = useState("");
  const hasEmpty = useMemo(
    () =>
      evidence.some(
        (item) =>
          !item.title || !item.sourceUrl || !item.publisher || !item.publishedAt || !item.excerpt,
      ),
    [evidence],
  );
  if (assumptions.length === 0) return null;
  async function submit() {
    setBusy(true);
    setMessage("");
    try {
      const response = await fetch(`/api/claims/${claimId}/review`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          evidence: evidence.map((item) => ({
            ...item,
            publishedAt: iso(item.publishedAt),
            retrievedAt: iso(item.retrievedAt),
            suppliedBy: "author",
          })),
        }),
      });
      const body = await response.json();
      if (!response.ok) throw new Error(body.error ?? "Review failed.");
      setMessage("Evidence review saved.");
      window.location.reload();
    } catch (error) {
      setMessage(error instanceof Error ? error.message : "Review failed.");
    } finally {
      setBusy(false);
    }
  }
  return (
    <section className="detail-panel replay-reasoning" aria-label="Evidence review">
      <span className="eyebrow">GROUNDED REASONING REVIEW</span>
      <h2>{review ? "Latest evidence assessment" : "Review the assumptions"}</h2>
      {review ? (
        <div className="assumption-list">
          {review.assumptionReviews.map((item) => (
            <div className="assumption" key={item.assumptionId}>
              <strong>
                {assumptions.find((assumption) => assumption.id === item.assumptionId)?.statement ??
                  item.assumptionId}
              </strong>
              <p>
                <b>{item.assessment}</b> — {item.explanation}
              </p>
              {item.evidenceIds.map((id) => {
                const source = review.evidence.find((entry) => entry.id === id);
                return source ? (
                  <p key={id}>
                    <a
                      className="text-link"
                      href={source.sourceUrl}
                      target="_blank"
                      rel="noopener noreferrer"
                    >
                      {source.title} · {source.publisher}
                    </a>
                    <small>{source.excerpt}</small>
                  </p>
                ) : null;
              })}
            </div>
          ))}
          <small>
            Generated by Claude from the supplied evidence. This review does not change the
            numerical performance result.
          </small>
        </div>
      ) : (
        <p>
          Attach dated, linked evidence to let Claude assess the saved assumptions. Evidence is
          supplied by you; MarkToThesis does not present model-generated sources as fact.
        </p>
      )}
      {canManage && (
        <div className="field-group">
          <label>Evidence items</label>
          {evidence.map((item, index) => (
            <div className="nested-field" key={item.id}>
              <input
                aria-label={`Evidence ${index + 1} title`}
                placeholder="Title"
                value={item.title}
                onChange={(event) =>
                  setEvidence((items) =>
                    items.map((current) =>
                      current.id === item.id ? { ...current, title: event.target.value } : current,
                    ),
                  )
                }
              />
              <input
                aria-label={`Evidence ${index + 1} URL`}
                placeholder="https://source.example/article"
                value={item.sourceUrl}
                onChange={(event) =>
                  setEvidence((items) =>
                    items.map((current) =>
                      current.id === item.id
                        ? { ...current, sourceUrl: event.target.value }
                        : current,
                    ),
                  )
                }
              />
              <input
                aria-label={`Evidence ${index + 1} publisher`}
                placeholder="Publisher"
                value={item.publisher}
                onChange={(event) =>
                  setEvidence((items) =>
                    items.map((current) =>
                      current.id === item.id
                        ? { ...current, publisher: event.target.value }
                        : current,
                    ),
                  )
                }
              />
              <input
                aria-label={`Evidence ${index + 1} publication date`}
                type="datetime-local"
                value={item.publishedAt}
                onChange={(event) =>
                  setEvidence((items) =>
                    items.map((current) =>
                      current.id === item.id
                        ? { ...current, publishedAt: event.target.value }
                        : current,
                    ),
                  )
                }
              />
              <textarea
                aria-label={`Evidence ${index + 1} excerpt`}
                placeholder="Short excerpt or observation"
                value={item.excerpt}
                onChange={(event) =>
                  setEvidence((items) =>
                    items.map((current) =>
                      current.id === item.id
                        ? { ...current, excerpt: event.target.value }
                        : current,
                    ),
                  )
                }
              />
            </div>
          ))}
          <button
            type="button"
            className="text-link"
            onClick={() => setEvidence((items) => [...items, newEvidence()])}
            disabled={evidence.length >= 12}
          >
            + Add evidence
          </button>
          <button
            type="button"
            className="button-primary"
            onClick={submit}
            disabled={busy || hasEmpty}
          >
            {busy ? "Reviewing…" : "Run Claude review"}
          </button>
          {message && <p className="field-help">{message}</p>}
        </div>
      )}
    </section>
  );
}
